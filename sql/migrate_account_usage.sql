CREATE TABLE IF NOT EXISTS `ai_usage_records` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `user_id` BIGINT UNSIGNED NOT NULL,
  `task_id` BIGINT UNSIGNED NULL,
  `image_id` BIGINT UNSIGNED NULL,
  `project_id` BIGINT UNSIGNED NULL,
  `project_name` VARCHAR(128) NOT NULL DEFAULT '',
  `task_name` VARCHAR(128) NOT NULL DEFAULT '',
  `image_name` VARCHAR(255) NOT NULL DEFAULT '',
  `model_name` VARCHAR(128) NOT NULL DEFAULT '',
  `cost` DECIMAL(12,4) NOT NULL DEFAULT 0,
  `action` VARCHAR(24) NOT NULL DEFAULT 'image_generation',
  `created_at` DATETIME NOT NULL,
  PRIMARY KEY (`id`), KEY `idx_usage_created` (`created_at`), KEY `idx_usage_user` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
